#!/usr/bin/env python3
"""Vendor the SmolVLA vehicle arm in its collision-checked navigation pose.

Run from any directory: python3 scripts/import_smolvla_model.py ../smolvla-demo
Only Python's standard library is required. Runtime does not depend on SmolVLA.
"""
import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import shutil
import subprocess
import xml.etree.ElementTree as ET
from xml.dom import minidom

PACKAGE = Path(__file__).resolve().parents[1] / 'src/simulate/simulate'
XACRO = 'http://www.ros.org/wiki/xacro'
ET.register_namespace('xacro', XACRO)


def rotation(rpy):
    r, p, y = rpy
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return [[cy*cp, cy*sp*sr-sy*cr, cy*sp*cr+sy*sr],
            [sy*cp, sy*sp*sr+cy*cr, sy*sp*cr-cy*sr], [-sp, cp*sr, cp*cr]]


def freeze(element, value):
    origin = element.find('origin')
    if element.get('type') == 'revolute':
        # All six upstream arm axes are +Z. Compose in the joint frame.
        assert [float(x) for x in element.find('axis').get('xyz').split()] == [0, 0, 1]
        a = rotation(map(float, origin.get('rpy', '0 0 0').split()))
        b = rotation((0, 0, value))
        c = [[sum(a[i][k]*b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
        pitch = math.atan2(-c[2][0], math.hypot(c[0][0], c[1][0]))
        if math.hypot(c[0][0], c[1][0]) < 1e-10:
            roll, yaw = math.atan2(-c[1][2], c[1][1]), 0.
        else:
            roll, yaw = math.atan2(c[2][1], c[2][2]), math.atan2(c[1][0], c[0][0])
        origin.set('rpy', ' '.join(format(x, '.15g') for x in (roll, pitch, yaw)))
    elif element.get('type') == 'prismatic':
        xyz = list(map(float, origin.get('xyz').split()))
        axis = list(map(float, element.find('axis').get('xyz').split()))
        origin.set('xyz', ' '.join(format(x+q*value, '.15g') for x, q in zip(xyz, axis)))
    element.set('type', 'fixed')
    for tag in ('axis', 'limit', 'dynamics'):
        for child in element.findall(tag):
            element.remove(child)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    source = args.source.resolve()
    spec = importlib.util.spec_from_file_location('smolvla_model', source/'block_pick_demo/model.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    tree = ET.parse(module.build_robot('vla'))
    root = tree.getroot()
    # Read the same initial joint configuration as the demo, without importing PyBullet.
    import ast
    simulation = ast.parse((source/'block_pick_demo/simulation.py').read_text())
    cls = next(n for n in simulation.body if isinstance(n, ast.ClassDef) and n.name == 'Simulation')
    fold = next(ast.literal_eval(n.value) for n in cls.body if isinstance(n, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == 'FOLD_Q' for t in n.targets))
    positions = dict(zip(module.ARM_JOINTS, fold))
    positions.update(left_finger_joint=.028, right_finger_joint=.028)
    arm_links = set()
    for link in root.findall('link'):
        if link.get('name') == 'g_base' or arm_links:
            arm_links.add(link.get('name'))
    output = ET.Element('robot')
    output.append(ET.Comment(' Generated by scripts/import_smolvla_model.py; SmolVLA vla camera profile, folded navigation pose. '))
    macro = ET.SubElement(output, '{%s}macro' % XACRO, name='smolvla_arm', params='parent prefix robot_namespace mesh_dir')
    assets = PACKAGE/'model/mycobot280'
    assets.mkdir(parents=True, exist_ok=True)
    copied = {}
    for node in root:
        if node.tag == 'link' and node.get('name') in arm_links:
            node.set('name', '${prefix}'+node.get('name'))
        elif node.tag == 'joint' and node.find('child').get('link') in arm_links:
            name = node.get('name')
            freeze(node, positions.get(name, 0.))
            node.set('name', '${prefix}'+name)
            parent = node.find('parent')
            parent.set('link', '${prefix}'+parent.get('link') if parent.get('link') in arm_links else '${parent}')
            child = node.find('child')
            child.set('link', '${prefix}'+child.get('link'))
        else:
            continue
        for mesh in node.iter('mesh'):
            name = Path(mesh.get('filename')).name
            mesh.set('filename', '${mesh_dir}/'+name)
            for asset_name in (name, Path(name).with_suffix('.png').name):
                asset = source/'assets/mycobot280'/asset_name
                shutil.copy2(asset, assets/asset_name)
                copied[asset_name] = hashlib.sha256(asset.read_bytes()).hexdigest()
        macro.append(node)
    for name in ('LICENSE', 'source.json'):
        shutil.copy2(source/'assets/mycobot280'/name, assets/name)
    # Gazebo Classic needs explicit script materials after fixed-joint reduction.
    for name, material in [('gripper_palm', 'Gazebo/DarkGrey'),
                           ('left_finger', 'Gazebo/Grey'), ('right_finger', 'Gazebo/Grey'),
                           ('wrist_camera_optical_frame', 'Gazebo/Blue')]:
        gazebo = ET.SubElement(macro, 'gazebo', reference='${prefix}'+name)
        ET.SubElement(gazebo, 'material').text = material
    # Gazebo cameras look along +X; the demo optical frame looks along +Z, with -Y up.
    gazebo = ET.SubElement(macro, 'gazebo', reference='${prefix}wrist_camera_optical_frame')
    sensor = ET.SubElement(gazebo, 'sensor', name='wrist_camera', type='camera')
    ET.SubElement(sensor, 'pose').text = '0 0 0 1.5707963267948966 -1.5707963267948966 0'
    ET.SubElement(sensor, 'always_on').text = 'true'
    ET.SubElement(sensor, 'update_rate').text = '15'
    camera = ET.SubElement(sensor, 'camera', name='wrist')
    ET.SubElement(camera, 'horizontal_fov').text = str(2*math.atan(math.tan(math.radians(75)/2)*4/3))
    image = ET.SubElement(camera, 'image')
    for tag, value in [('width','320'), ('height','240'), ('format','R8G8B8')]:
        ET.SubElement(image, tag).text = value
    clip = ET.SubElement(camera, 'clip')
    ET.SubElement(clip, 'near').text = '0.02'
    ET.SubElement(clip, 'far').text = '3'
    plugin = ET.SubElement(sensor, 'plugin', name='wrist_camera_controller', filename='libgazebo_ros_camera.so')
    ros = ET.SubElement(plugin, 'ros')
    ET.SubElement(ros, 'namespace').text = '${robot_namespace}'
    # Foxy prefixes camera topics with camera_name before applying ROS remaps.
    for remapping in ('wrist_camera/image_raw:=camera/wrist/image_raw',
                      'wrist_camera/camera_info:=camera/wrist/camera_info'):
        ET.SubElement(ros, 'remapping').text = remapping
    ET.SubElement(plugin, 'camera_name').text = 'wrist_camera'
    ET.SubElement(plugin, 'frame_name').text = '${prefix}wrist_camera_optical_frame'
    for element in output.iter():
        if element.text is not None and not element.text.strip():
            element.text = None
        element.tail = None
    xml = minidom.parseString(ET.tostring(output)).toprettyxml(indent='  ')
    (PACKAGE/'urdf/smolvla_arm.urdf.xacro').write_text(xml)
    provenance = dict(source_repository='https://github.com/Yu-Linbo/smolvla-demo',
                      source_commit=subprocess.check_output(['git','-C',str(source),'rev-parse','HEAD'], text=True).strip(),
                      camera_profile='vla', arm_joint_positions=positions,
                      source_sha256={str(p.relative_to(source)): hashlib.sha256(p.read_bytes()).hexdigest()
                                     for p in (source/'block_pick_demo/model.py', source/'block_pick_demo/simulation.py')},
                      sha256=copied)
    (assets/'smolvla-source.json').write_text(json.dumps(provenance, indent=2)+'\n')
    print('Imported SmolVLA folded arm, gripper, wrist camera and %d mesh/texture assets' % len(copied))


if __name__ == '__main__':
    main()
